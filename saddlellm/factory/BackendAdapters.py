"""Backend adapter specs and launch-script generation.

These adapters do not replace the orchestrator.  They make backend choices
explicit and produce reproducible launch commands for local, Accelerate,
DeepSpeed, Megatron-style, and Colossal-style execution paths.
"""

import json
import os
import re
import sys
import uuid
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Any, Dict, List, Optional


@dataclass
class LaunchPlan:
    backend: str
    command: List[str]
    launcher: str = "accelerate"
    topology: Dict[str, Any] = field(default_factory=dict)
    env: Dict[str, str] = field(default_factory=dict)
    notes: List[str] = field(default_factory=list)
    script_path: Optional[str] = None

    def to_dict(self) -> Dict:
        return asdict(self)


class BackendAdapterRegistry:
    """Create launch plans for SaddleLLM and external-style backends."""

    @staticmethod
    def create_launch_plan(
        config_path: str,
        backend: str = "auto",
        num_gpus: int = 1,
        num_nodes: int = 1,
        backend_plan_path: Optional[str] = None,
        launcher: str = "accelerate",
    ) -> LaunchPlan:
        if backend == "auto":
            backend = BackendAdapterRegistry._infer_backend(
                config_path, backend_plan_path
            )
        backend = BackendAdapterRegistry._normalize_backend_name(backend)
        if int(num_gpus) < 1 or int(num_nodes) < 1:
            raise ValueError("num_gpus and num_nodes must be >= 1")
        launcher = str(launcher).strip().lower()
        if launcher not in {"accelerate", "torchrun"}:
            raise ValueError("launcher must be 'accelerate' or 'torchrun'")

        if backend in {
            "single",
            "torch_ddp",
            "torch_fsdp",
            "deepspeed_zero2",
            "deepspeed_zero3",
        }:
            return BackendAdapterRegistry._distributed_plan(
                config_path, backend, num_gpus, num_nodes, launcher
            )
        if backend in {"hybrid_parallel", "moe_hybrid_parallel"}:
            raise NotImplementedError(
                "Hybrid TP/PP/CP/EP launch requires a runtime adapter; "
                "no executable fallback is generated"
            )
        raise ValueError(f"Unknown backend: {backend}")

    @staticmethod
    def _normalize_backend_name(backend: str) -> str:
        aliases = {
            "ddp": "torch_ddp",
            "fsdp": "torch_fsdp",
            "deepspeed": "deepspeed_zero2",
        }
        return aliases.get(backend, backend)

    @staticmethod
    def save_launch_script(plan: LaunchPlan, path: str) -> str:
        os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
        lines = ["# Auto-generated by SaddleLLM", "$ErrorActionPreference = 'Stop'", ""]
        for key, value in plan.env.items():
            if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", str(key)) is None:
                raise ValueError(f"invalid environment variable name: {key!r}")
            escaped = str(value).replace("'", "''")
            lines.append(f"$env:{key} = '{escaped}'")
        cmd = " ".join(BackendAdapterRegistry._quote(arg) for arg in plan.command)
        lines.append("& " + cmd)
        lines.append("exit $LASTEXITCODE")
        BackendAdapterRegistry._atomic_write(
            path, "\n".join(lines) + "\n", encoding="utf-8-sig"
        )
        plan.script_path = path
        return path

    @staticmethod
    def save_launch_plan(plan: LaunchPlan, path: str) -> str:
        os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
        BackendAdapterRegistry._atomic_write(
            path,
            json.dumps(plan.to_dict(), ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
        )
        return path

    @staticmethod
    def _atomic_write(path: str, content: str, *, encoding: str) -> None:
        destination = Path(path)
        temporary = destination.with_name(
            f"{destination.name}.{os.getpid()}.{uuid.uuid4().hex}.tmp"
        )
        try:
            temporary.write_text(content, encoding=encoding)
            os.replace(temporary, destination)
        finally:
            if temporary.exists():
                temporary.unlink()

    @staticmethod
    def _distributed_plan(
        config_path: str,
        backend: str,
        num_gpus: int,
        num_nodes: int = 1,
        launcher: str = "accelerate",
    ) -> LaunchPlan:
        world_size = int(num_gpus) * int(num_nodes)
        topology = {
            "num_gpus_per_node": int(num_gpus),
            "num_nodes": int(num_nodes),
            "world_size": world_size,
        }
        if backend == "single":
            return LaunchPlan(
                backend="single",
                command=[
                    sys.executable,
                    "-m",
                    "saddlellm.cli",
                    "train",
                    os.path.abspath(config_path),
                ],
                launcher="python",
                topology=topology,
                notes=["Single-process launch through TrainingOrchestrator."],
            )
        if world_size < 2:
            raise ValueError(f"backend={backend!r} requires at least 2 processes")
        machine_rank = BackendAdapterRegistry._machine_rank()
        main_ip = BackendAdapterRegistry._main_process_ip()
        main_port = os.environ.get(
            "MAIN_PROCESS_PORT", os.environ.get("MASTER_PORT", "29500")
        )
        try:
            parsed_port = int(main_port)
        except ValueError as exc:
            raise ValueError(
                f"main process port must be an integer, got {main_port!r}"
            ) from exc
        if not 1 <= parsed_port <= 65535:
            raise ValueError("main process port must be in the range 1..65535")
        main_port = str(parsed_port)
        if machine_rank is not None and not 0 <= machine_rank < int(num_nodes):
            raise ValueError(
                f"machine rank {machine_rank} is outside num_nodes={num_nodes}"
            )

        if launcher == "accelerate":
            # Backend-specific settings are supplied through Transformers
            # TrainingArguments. Passing --use_deepspeed/--use_fsdp here as
            # well creates a second, potentially conflicting configuration.
            command = [
                sys.executable,
                "-m",
                "accelerate.commands.launch",
                "--multi_gpu",
                "--num_processes",
                str(world_size),
                "--num_machines",
                str(num_nodes),
            ]
            if num_nodes > 1:
                if machine_rank is None or main_ip is None:
                    raise ValueError(
                        "multi-node launch requires MACHINE_RANK and MAIN_PROCESS_IP "
                        "(or scheduler-provided RANK/MASTER_ADDR)"
                    )
                command.extend(
                    [
                        "--machine_rank",
                        str(machine_rank),
                        "--main_process_ip",
                        str(main_ip),
                        "--main_process_port",
                        str(main_port),
                    ]
                )
            command.extend(
                ["-m", "saddlellm.cli", "train", os.path.abspath(config_path)]
            )
        else:
            command = [
                sys.executable,
                "-m",
                "torch.distributed.run",
                "--nnodes",
                str(num_nodes),
                "--nproc-per-node",
                str(num_gpus),
            ]
            if num_nodes > 1:
                if machine_rank is None or main_ip is None:
                    raise ValueError(
                        "multi-node launch requires MACHINE_RANK and MAIN_PROCESS_IP "
                        "(or scheduler-provided RANK/MASTER_ADDR)"
                    )
                command.extend(
                    [
                        "--node-rank",
                        str(machine_rank),
                        "--master-addr",
                        str(main_ip),
                        "--master-port",
                        str(main_port),
                    ]
                )
            command.extend(
                ["-m", "saddlellm.cli", "train", os.path.abspath(config_path)]
            )
        notes = [
            f"Uses {launcher} for process launch; Trainer config selects "
            f"backend {backend}."
        ]
        if backend.startswith("deepspeed"):
            notes.append(
                "DeepSpeed ZeRO stage comes from the resolved TrainingArguments config."
            )
        if world_size >= 64:
            notes.append(
                "Large-scale data parallel plan: benchmark network collectives "
                "and use a hybrid TP/PP/CP/EP runtime when model or communication "
                "scaling requires it."
            )
        return LaunchPlan(
            backend=backend,
            command=command,
            launcher=launcher,
            topology=topology,
            notes=notes,
        )

    @staticmethod
    def _machine_rank() -> Optional[int]:
        for name in ("MACHINE_RANK", "GROUP_RANK", "NODE_RANK", "SLURM_NODEID"):
            raw = os.environ.get(name)
            if raw not in {None, ""}:
                try:
                    return int(raw)
                except ValueError as exc:
                    raise ValueError(f"{name} must be an integer, got {raw!r}") from exc
        rank = os.environ.get("RANK")
        local_world_size = os.environ.get("LOCAL_WORLD_SIZE")
        if rank not in {None, ""} and local_world_size not in {None, ""}:
            try:
                return int(rank) // int(local_world_size)
            except (ValueError, ZeroDivisionError) as exc:
                raise ValueError(
                    "RANK and LOCAL_WORLD_SIZE must describe a valid topology"
                ) from exc
        return None

    @staticmethod
    def _main_process_ip() -> Optional[str]:
        return os.environ.get("MAIN_PROCESS_IP") or os.environ.get("MASTER_ADDR")

    @staticmethod
    def _hybrid_plan(
        config_path: str,
        backend: str,
        num_gpus: int,
        backend_plan_path: Optional[str],
    ) -> LaunchPlan:
        notes = [
            "Hybrid TP/PP/CP/EP execution requires a Megatron/Colossal "
            "runtime adapter.",
            "This script is a handoff plan and uses SaddleLLM config as the "
            "source of truth.",
        ]
        command = [
            "torchrun",
            "--nproc_per_node",
            str(num_gpus),
            "-m",
            "saddle_llm.cli",
            "train",
            config_path,
        ]
        if backend_plan_path:
            notes.append(f"Backend plan: {backend_plan_path}")
        return LaunchPlan(backend=backend, command=command, notes=notes)

    @staticmethod
    def _infer_backend(config_path: str, backend_plan_path: Optional[str]) -> str:
        if backend_plan_path and os.path.exists(backend_plan_path):
            with open(backend_plan_path, "r", encoding="utf-8") as f:
                return json.load(f).get("plan", {}).get("backend", "single")
        try:
            with open(config_path, "r", encoding="utf-8") as f:
                if config_path.lower().endswith((".yaml", ".yml")):
                    import yaml

                    data = yaml.safe_load(f) or {}
                else:
                    data = json.load(f)
            return data.get("distributed", data.get("backend", {})).get(
                "strategy", "single"
            )
        except Exception:
            return "single"

    @staticmethod
    def _quote(value: str) -> str:
        return "'" + str(value).replace("'", "''") + "'"
